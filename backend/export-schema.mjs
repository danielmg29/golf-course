// Stands in for Django's `manage.py export_schema` (manual 3.1 and 6.4).
//
// Reads backend/models/*.json, which use Django's field classes and option names,
// and writes the generated contract plus the table registry the repository reads.
// Output must stay deterministic: `npm run verify` diffs it against git.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const backendDir = dirname(fileURLToPath(import.meta.url));
const schemaOut = join(backendDir, "..", "lib", "generated", "schema.ts");
const tablesOut = join(backendDir, "tables.generated.ts");

const HEADER = [
  "// AUTO-GENERATED by `npm run schema` from backend/models/*.json.",
  "// DO NOT EDIT: changes are overwritten on every dev and build.",
  "",
].join("\n");

function fail(message) {
  console.error(`export-schema: ${message}`);
  process.exit(1);
}

const maxLength = ({ max_length: max }) => (max === undefined ? "" : `.max(${max})`);

const range = ({ min_value: min, max_value: max }) =>
  `${min === undefined ? "" : `.min(${min})`}${max === undefined ? "" : `.max(${max})`}`;

// Django field class -> Zod type, data type and widget.
const FIELD_CLASSES = {
  AutoField: () => ({ zod: "z.number().int()", type: "integer", widget: "number", readOnly: true }),
  CharField: (f) => ({ zod: `z.string()${maxLength(f)}`, type: "string", widget: "text" }),
  SlugField: (f) => ({ zod: `z.string().regex(/^[a-z0-9-]+$/)${maxLength(f)}`, type: "string", widget: "slug" }),
  TextField: () => ({ zod: "z.string()", type: "string", widget: "textarea" }),
  EmailField: () => ({ zod: "z.email()", type: "string", widget: "email" }),
  URLField: () => ({ zod: "z.url()", type: "string", widget: "url" }),
  IntegerField: (f) => ({ zod: `z.number().int()${range(f)}`, type: "integer", widget: "number" }),
  PositiveIntegerField: (f) => ({ zod: `z.number().int()${range({ min_value: 0, ...f })}`, type: "integer", widget: "number" }),
  DecimalField: (f) => ({ zod: `z.number()${range(f)}`, type: "decimal", widget: "currency" }),
  BooleanField: () => ({ zod: "z.boolean()", type: "boolean", widget: "switch" }),
  DateField: () => ({ zod: "z.iso.date()", type: "date", widget: "date" }),
  DateTimeField: (f) => ({ zod: "z.iso.datetime()", type: "datetime", widget: "datetime", readOnly: Boolean(f.auto_now_add) }),
};

function humanise(name) {
  const words = name.replaceAll("_", " ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}

function compileField(model, field, index) {
  const compile = FIELD_CLASSES[field.field];
  if (!compile) fail(`${model.name}.${field.name}: unknown field class "${field.field}".`);

  const { zod: baseZod, type, widget, readOnly = false } = compile(field);
  const choices = field.choices?.map(([value, label]) => ({ value, label }));
  const hasDefault = field.default !== undefined;

  let zod = choices ? `z.enum(${JSON.stringify(choices.map((c) => c.value))})` : baseZod;
  if (readOnly) zod += ".readonly()";
  if (hasDefault) zod += `.default(${JSON.stringify(field.default)})`;
  else if (field.blank) zod += ".optional()";

  const { list_fields: listFields = [], filter_fields: filterFields = [] } = model.adaptive;
  const meta = {
    name: field.name,
    type: choices ? "enum" : type,
    widget: choices ? "select" : widget,
    label: field.verbose_name ?? humanise(field.name),
    required: !(readOnly || hasDefault || field.blank),
    readOnly,
    inList: listFields.includes(field.name),
    inFilter: filterFields.includes(field.name),
    weight: (index + 1) * 10,
    ...(field.derives_from ? { derivesFrom: field.derives_from } : {}),
    ...(choices ? { choices } : {}),
  };

  return { zod, meta };
}

function checkReferences(model) {
  const known = new Set(model.fields.map((f) => f.name));
  const { display_field: display, list_fields: list = [], filter_fields: filter = [] } = model.adaptive;
  const ordering = (model.ordering ?? []).map((name) => name.replace(/^-/, ""));

  for (const name of [display, ...list, ...filter, ...ordering]) {
    if (!known.has(name)) fail(`${model.name}: "${name}" is referenced but is not a field.`);
  }
}

function compileModel(file) {
  const key = basename(file, ".json");
  if (!/^[a-z][a-z0-9_]*$/.test(key)) fail(`${file}: model file names must be lower_snake_case.`);

  const model = JSON.parse(readFileSync(join(backendDir, "models", file), "utf8"));
  checkReferences(model);

  const primaryKey = model.fields.find((f) => f.field === "AutoField")?.name;
  if (!primaryKey) fail(`${model.name}: needs an AutoField as its primary key.`);

  const fixture = join(backendDir, "fixtures", file);
  if (!existsSync(fixture)) fail(`${model.name}: missing backend/fixtures/${file}.`);
  if (!Array.isArray(JSON.parse(readFileSync(fixture, "utf8")))) {
    fail(`backend/fixtures/${file} must be a JSON array of rows.`);
  }

  const compiled = model.fields.map((field, index) => compileField(model, field, index));
  const adaptive = model.adaptive;
  const meta = {
    name: model.name,
    label: model.verbose_name ?? humanise(model.name),
    labelPlural: model.verbose_name_plural ?? `${humanise(model.name)}s`,
    primaryKey,
    displayField: adaptive.display_field,
    tenantField: adaptive.tenant_field ?? null,
    ordering: model.ordering ?? [],
    fields: compiled.map((c) => c.meta),
    actions: adaptive.immutable ? [] : ["create", "update", "delete", "export"],
  };

  const shape = model.fields.map((f, i) => `  ${f.name}: ${compiled[i].zod},`).join("\n");
  const source = [
    `export const ${model.name}Schema = z.object({`,
    shape,
    "});",
    `export type ${model.name} = z.infer<typeof ${model.name}Schema>;`,
    "",
    `export const ${model.name}Meta = ${JSON.stringify(meta, null, 2)} as const satisfies ModelMeta;`,
    "",
  ].join("\n");

  return { key, name: model.name, source };
}

const files = readdirSync(join(backendDir, "models")).filter((f) => f.endsWith(".json")).sort();
const models = files.map(compileModel);

const schema = [
  HEADER,
  'import { z } from "zod";',
  'import type { ModelMeta } from "@/lib/contract";',
  "",
  'export type { FieldMeta, ModelMeta } from "@/lib/contract";',
  "",
  ...models.map((m) => m.source),
  "export const contract = {",
  ...models.map((m) => `  ${m.key}: { schema: ${m.name}Schema, meta: ${m.name}Meta },`),
  "} as const;",
  "",
  "export type ModelName = keyof typeof contract;",
  "",
].join("\n");

const tables = [
  HEADER,
  ...models.map((m) => `import ${m.key} from "./fixtures/${m.key}.json";`),
  "",
  `export const tables = { ${models.map((m) => m.key).join(", ")} };`,
  "",
].join("\n");

mkdirSync(dirname(schemaOut), { recursive: true });
writeFileSync(schemaOut, schema);
writeFileSync(tablesOut, tables);
console.log(`export-schema: wrote the contract for ${models.length} model(s).`);
